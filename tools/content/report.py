"""Short human-readable build report (content/build-report.md)."""
import collections


def coverage(src, inc):
    """Per pack and language: how many texts exist."""
    from .common import walk_lt
    locs = [l['tag'] for l in src.cfg['locales']['locales']]
    out = {}
    for pid, P in src.packs.items():
        n = collections.Counter(); tot = 0
        for rid in P['records']:
            if rid not in inc: continue
            r = src.records[rid]
            for _, lt in walk_lt({'p': r['payload'], 't': r['tags']}, set(locs)):
                tot += 1
                for lg in lt: n[lg] += 1
        out[pid] = (tot, {lg: n[lg] for lg in locs})
    return out


def render(src, val, build, issues, check_ok=None):
    err = [i for i in issues if i.sev == 'error']
    warn = [i for i in issues if i.sev == 'warn']
    info = [i for i in issues if i.sev == 'info']
    cat = build.catalog if build else None
    L = []
    A = L.append
    A('# Content library build report')
    A('')
    A('Generated by `python3 tools/content_build.py` (do not edit). Plain summary first, details below.')
    A('')
    if cat:
        A(f'- **Release:** sequence {cat["sequence"]}, channel `{cat["channel"]}`, issued {cat["issued"]} (UTC)')
    inc = build.recs if build else {}
    types = collections.Counter(r['type'] for r in inc.values())
    stat = collections.Counter(r['status'] for r in inc.values())
    A(f'- **Records:** {len(inc)} in this channel ({", ".join(f"{v} {k}" for k, v in sorted(types.items()))})')
    A(f'- **Status:** {", ".join(f"{v} {k}" for k, v in sorted(stat.items()))}')
    legacy_n = sum(1 for r in inc.values() if r.get('review', {}).get('legacy'))
    if legacy_n:
        A(f'- **Not yet re-reviewed:** {legacy_n} records were live before the review workflow (marked legacy).')
    A(f'- **Checks:** {len(err)} errors, {len(warn)} warnings, {len(info)} notes. ' + ('**Build OK.**' if not err else '**Build FAILED.**'))
    if getattr(val, 'stats', None):
        A(f'- **Voice:** {val.stats.get("spoken", 0)} spoken lines, {val.stats.get("voiceMissing", 0)} without a voice clip.')
    if check_ok is not None:
        A(f'- **Committed library up to date:** {"yes" if check_ok else "NO - run python3 tools/content_build.py"}')
    A('')
    A('## Languages (texts present / texts in pack)')
    A('')
    cov = coverage(src, set(inc))
    locs = [l['tag'] for l in src.cfg['locales']['locales']]
    A('| Pack | Required | ' + ' | '.join(locs) + ' |')
    A('|---|---|' + '---|' * len(locs))
    for pid, (tot, n) in cov.items():
        req = ', '.join(src.packs[pid]['meta']['locales']['required'])
        A(f'| {pid} | {req} | ' + ' | '.join(f'{n[lg]}/{tot} ({(100 * n[lg] // tot) if tot else 100}%)' for lg in locs) + ' |')
    A('')
    A('A required language must be 100% (else the build fails). Other languages show how far translation has got.')
    A('')
    if build and build.stats:
        A('## Packs (what the app downloads)')
        A('')
        A('| Pack | Records | Texts | Structure | Languages | Pictures + voice it needs |')
        A('|---|---|---|---|---|---|')
        for pid, s in build.stats.items():
            lg = ', '.join(f'{k} {b/1024:.1f} KB' for k, (b, c) in s['locales'].items())
            A(f'| {pid} | {s["records"]} | {s["strings"]} | {s["bytes"]/1024:.1f} KB | {lg} | {s["assets"]} files, {s["assetBytes"]/1e6:.1f} MB |')
        A('')
    if build and (build.pruned or build.notes):
        A('## Left out of this channel')
        A('')
        for n in build.pruned: A(f'- pruned link: {n}')
        for n in build.notes: A(f'- {n}')
        A('')
    for title, items in (('Errors (must fix)', err), ('Warnings (need a human decision)', warn), ('Notes', info)):
        if not items: continue
        A(f'## {title}')
        A('')
        by = collections.defaultdict(list)
        for i in items: by[i.code].append(i)
        for code, xs in sorted(by.items()):
            A(f'- **{code}** ({len(xs)})')
            for i in xs[:12]:
                A(f'  - {i.where}: {i.msg}')
            if len(xs) > 12: A(f'  - ... {len(xs) - 12} more')
        A('')
    return '\n'.join(L) + '\n'
